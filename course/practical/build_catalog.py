"""Embed authored practical guides for offline viewing. Run --check in verification."""
import argparse
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT.parent / "practical-data.js"


def inline(text):
    tokens = []
    def protect(match):
        raw = match.group(0)
        if raw.startswith("`"):
            value = "<code>"+html.escape(raw[1:-1])+"</code>"
        else:
            link = re.fullmatch(r"\[([^\]]+)\]\((https?://[^\s)]+)\)", raw)
            value = '<a href="'+html.escape(link[2], quote=True)+'" target="_blank" rel="noopener">'+html.escape(link[1])+" ↗</a>"
        tokens.append(value)
        return f"@@PRACTICAL{len(tokens)-1}@@"
    escaped = html.escape(re.sub(r"`[^`]+`|\[[^\]]+\]\(https?://[^\s)]+\)", protect, text))
    escaped = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", escaped)
    for i, token in enumerate(tokens):
        escaped = escaped.replace(f"@@PRACTICAL{i}@@", token)
    return escaped


def markdown(text):
    output, paragraph = [], []
    code = None
    def flush():
        if paragraph:
            output.append("<p>"+inline(" ".join(paragraph))+"</p>")
            paragraph.clear()
    for line in text.splitlines():
        if line.startswith("```"):
            flush()
            if code is None:
                code = []
            else:
                output.append('<pre tabindex="0"><code>'+html.escape("\n".join(code))+"</code></pre>")
                code = None
        elif code is not None:
            code.append(line)
        elif re.match(r"^#{1,3} ", line):
            flush()
            level, title = line.split(" ", 1)
            if len(level) > 1:  # The app supplies the page's single h1.
                output.append(f"<h{len(level)}>"+inline(title)+f"</h{len(level)}>")
        elif not line.strip():
            flush()
        else:
            paragraph.append(line)
    flush()
    if code is not None:
        raise ValueError("Unclosed fenced code block")
    return "\n".join(output)


def build():
    labs = json.loads((ROOT/"manifest.json").read_text(encoding="utf-8"))
    for lab in labs:
        lab["html"] = markdown((ROOT/lab["file"]).read_text(encoding="utf-8"))
    payload = json.dumps(labs, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    return "// Generated by practical/build_catalog.py; edit practical/labs/*.md.\nwindow.CV_PRACTICAL_DATA = "+payload+";\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = build()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            raise SystemExit("Practical catalog is stale. Run python course/practical/build_catalog.py")
        print("Practical catalog matches all 12 source guides.")
    else:
        OUTPUT.write_text(expected, encoding="utf-8")
        print("Built", OUTPUT)
