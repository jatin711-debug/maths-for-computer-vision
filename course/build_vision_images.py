"""Embed the sample photographs used by the image experiments: python course/build_vision_images.py

The images come from scikit-image's bundled sample data, all released without copyright restrictions (CC0 or public domain).
They are embedded as data URIs so the experiments also work when index.html is opened directly from disk, where a
canvas cannot read pixels from separate local image files.
"""
from base64 import b64encode
from io import BytesIO
from pathlib import Path
import json

from PIL import Image
import skimage.data as data

TARGET = Path(__file__).with_name('vision-images.js')


def encode(image, fmt, **options):
    buffer = BytesIO()
    image.save(buffer, fmt, optimize=True, **options)
    mime = 'image/png' if fmt == 'PNG' else 'image/jpeg'
    return f'data:{mime};base64,' + b64encode(buffer.getvalue()).decode('ascii')


def crop_to(image, width, height, focus=(0.5, 0.5)):
    """Scale to cover width x height, then crop around a relative focus point."""
    scale = max(width / image.width, height / image.height)
    resized = image.resize((round(image.width * scale), round(image.height * scale)), Image.LANCZOS)
    left = min(max(0, round(resized.width * focus[0] - width / 2)), resized.width - width)
    top = min(max(0, round(resized.height * focus[1] - height / 2)), resized.height - height)
    return resized.crop((left, top, left + width, top + height))


images = {
    'camera': dict(src=encode(Image.fromarray(data.camera()).resize((256, 256), Image.LANCZOS), 'PNG'), width=256, height=256,
                   title='Cameraman', credit='Lav Varshney, CC0 (scikit-image sample data)'),
    'brick': dict(src=encode(Image.fromarray(data.brick()).resize((256, 256), Image.LANCZOS), 'PNG'), width=256, height=256,
                  title='Brick wall seen in perspective', credit='CC0Textures Bricks25, CC0 (scikit-image sample data)'),
    'cat': dict(src=encode(crop_to(Image.fromarray(data.chelsea()), 224, 160, (0.48, 0.5)), 'JPEG', quality=88), width=224, height=160,
                title='Chelsea the cat', credit='Stéfan van der Walt, CC0 (scikit-image sample data)'),
    'coffee': dict(src=encode(crop_to(Image.fromarray(data.coffee()), 240, 160, (0.5, 0.45)), 'JPEG', quality=88), width=240, height=160,
                   title='Coffee cup', credit='Rachel Michetti, CC0 (scikit-image sample data)'),
}
TARGET.write_text('// Generated by build_vision_images.py from scikit-image sample photographs (CC0 / no copyright restrictions).\n'
                  'window.CV_IMAGES = ' + json.dumps(images, indent=1) + ';\n', encoding='utf-8')
print(f'Wrote {TARGET.name}: {", ".join(f"{k} {v["width"]}x{v["height"]}" for k, v in images.items())}; {TARGET.stat().st_size // 1024} KB')
