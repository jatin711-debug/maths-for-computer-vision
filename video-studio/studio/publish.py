"""Renders a compiled video, verifies the file, and adds it to the course."""
import hashlib, json, re, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COURSE = ROOT.parent / 'course'
OUT = COURSE / 'media' / 'fframes'
DATA = COURSE / 'explainer-video-data.js'
PREFIX = 'window.CV_EXPLAINER_VIDEO_DATA = '
HEADER = '// Generated by video-studio (python -m studio <storyboard> publish) from every storyboard, keeping earlier entries.\n'


def stamp(seconds):
    hours, rest = divmod(seconds, 3600)
    minutes, secs = divmod(rest, 60)
    return f'{int(hours):02d}:{int(minutes):02d}:{secs:06.3f}'


def caption_lines(text, width=42):
    lines, line = [], ''
    for word in text.split():
        if len(line) + len(word) + 1 > width and line:
            lines.append(line)
            line = word
        else:
            line = f'{line} {word}'.strip()
    return lines + [line]


def split_sentence(text, limit=84):
    """A long sentence becomes several cues, breaking at punctuation where it can."""
    if len(text) <= limit: return [text]
    parts, current = [], ''
    for piece in re.split(r'(?<=[,;:])\s+', text):
        if current and len(current) + len(piece) + 1 > limit:
            parts.append(current)
            current = piece
        else:
            current = f'{current} {piece}'.strip()
    return parts + [current]


def vtt(info):
    lines = ['WEBVTT', '']
    for chapter in info['chapters']:
        for start, end, text in chapter['captions']:
            parts, at = split_sentence(text), start
            whole = sum(len(part) for part in parts)
            for part in parts:
                stop = at + (end - start) * len(part) / whole
                lines += [f'{stamp(at)} --> {stamp(stop)}', *caption_lines(part), '']
                at = stop + .001
    return '\n'.join(lines)


def run(command, env=None, cwd=None):
    result = subprocess.run([str(c) for c in command], env=env, cwd=cwd, capture_output=True, text=True, encoding='utf8', errors='replace')
    if result.returncode: sys.exit(f'{command[0]} failed:\n{result.stderr[-1500:]}')
    return result


def course_module(lesson):
    text = (COURSE / 'course-data.js').read_text(encoding='utf8').removeprefix('window.CV_COURSE = ').rstrip().rstrip(';').replace('<\\/', '</')
    return next(l['module'] for l in json.loads(text)['lessons'] if l['id'] == lesson)


def add_to_course(entry):
    text = DATA.read_text(encoding='utf8')
    items = json.loads(text[text.index(PREFIX) + len(PREFIX):].rstrip().rstrip(';'))
    items = [item for item in items if item['id'] != entry['id']] + [entry]
    items.sort(key=lambda item: (item['lesson'], item['id']))
    DATA.write_text(HEADER + PREFIX + json.dumps(items, indent=1, ensure_ascii=False) + ';\n', encoding='utf8')


def publish(video, info, env):
    key = video.key
    raw, final = video.dir / 'raw.mp4', OUT / f'{key}.mp4'
    binary = ROOT / 'target' / 'release' / 'cv-studio.exe'
    run([binary, 'render', '-o', raw], env, video.dir)
    run(['ffmpeg', '-y', '-v', 'error', '-i', raw, '-c', 'copy', '-movflags', '+faststart', final], env)

    probe = json.loads(run(['ffprobe', '-v', 'error', '-count_packets', '-show_streams', '-show_format', '-of', 'json', final], env).stdout)
    picture = next(s for s in probe['streams'] if s['codec_type'] == 'video')
    sound = next(s for s in probe['streams'] if s['codec_type'] == 'audio')
    frames = int(picture['nb_read_packets'])
    if frames != info['frames']: sys.exit(f'{key}: {frames} frames, expected {info["frames"]}')
    if (picture['width'], picture['height'], picture['pix_fmt']) != (1920, 1080, 'yuv420p'): sys.exit(f'{key}: unexpected picture {picture["width"]}x{picture["height"]} {picture["pix_fmt"]}')
    errors = run(['ffmpeg', '-v', 'error', '-i', final, '-f', 'null', '-'], env).stderr.strip()
    if errors: sys.exit(f'{key}: decode errors\n{errors[:600]}')
    log = run(['ffmpeg', '-hide_banner', '-nostats', '-i', final, '-map', '0:a', '-af', 'ebur128=peak=true', '-f', 'null', '-'], env).stderr
    lufs = float(re.findall(r'I:\s+(-?[\d.]+) LUFS', log)[-1])
    peak = float(re.findall(r'Peak:\s+(-?[\d.]+) dBFS', log)[-1])
    if not -16 <= lufs <= -12 or peak > -.5: sys.exit(f'{key}: loudness {lufs} LUFS, peak {peak} dBFS')

    poster_at = getattr(video, 'poster_at', None) or info['chapters'][1]['end'] - .6
    poster = OUT / f'{key}.png'
    run(['ffmpeg', '-y', '-v', 'error', '-ss', f'{poster_at:.2f}', '-i', final, '-frames:v', '1', '-vf', 'scale=1280:-1', poster], env)
    (OUT / f'{key}.vtt').write_text(vtt(info), encoding='utf8')

    digest = hashlib.sha256(final.read_bytes()).hexdigest()
    version = digest[:12]
    add_to_course(dict(id=f'fframes-{key}', key=key, title=video.title, module=course_module(video.lesson), lesson=video.lesson, animated=True, duration=info['duration'],
                       src=f'media/fframes/{key}.mp4?v={version}', poster=f'media/fframes/{key}.png?v={version}', captions=f'media/fframes/{key}.vtt?v={version}',
                       chapters=[{k: ch[k] for k in ('label', 'name', 'time', 'end', 'frames', 'narration')} for ch in info['chapters']]))
    size = final.stat().st_size / 1e6
    print(f'Published {key}: {info["duration"]:.1f}s, {frames} frames, {size:.1f} MB, {picture["codec_name"]}/{sound["codec_name"]} {sound["sample_rate"]} Hz, {lufs} LUFS, peak {peak} dBFS')
